package it.g03.orders

import jakarta.persistence.*
import java.time.Instant
import java.util.UUID

/**
 * The saga aggregate. Order state machine (Pillar A/B):
 *
 *   PENDING -- reserve ok --> RESERVED -- authorize ok + confirm ok --> CONFIRMED
 *      |                        |
 *      |-- reserve sold-out --> REJECTED(SOLD_OUT)
 *                               |-- authorize declined --> REJECTED(PAYMENT_DECLINED) (+release)
 *                               |-- hold expired before confirm --> REJECTED(RESERVATION_EXPIRED)
 *
 * PENDING/RESERVED are RESUMABLE states: an at-least-once redelivery of order-placed re-enters the saga from where it crashed (every downstream step is idempotent)
 * CONFIRMED/REJECTED are terminal: replays become no-ops
 * (Phase 2 adds a PAYMENT_PENDING parking state as the circuit-breaker fallback)
 */

@Entity // maps this class to a database table (JPA entity)
@Table(name = "orders")
data class Order(
    // primary key (UUID): generated by the application to avoid a shared DB sequence bottleneck under high concurrency
    @Id
    val id: UUID = UUID.randomUUID(),

    // product being bought (shared productId vocabulary with Catalog / Inventory)
    @Column(name = "product_id", nullable = false, length = 64)
    val productId: String = "",

    // how many units were requested
    @Column(nullable = false)
    val qty: Int = 0,

    // total price in cents (qty * unit price) [computed at placement time]
    @Column(name = "amount_cents", nullable = false)
    val amountCents: Long = 0,

    // current state in the saga state machine; mutated as the saga advances
    @Enumerated(EnumType.STRING) // store the enum by NAME (not ordinal) so the column stays readable and stable (as always)
    @Column(nullable = false, length = 16)
    var status: OrderStatus = OrderStatus.PENDING,

    // Why a REJECTED order was rejected (null otherwise)
    @Enumerated(EnumType.STRING) // store the enum by NAME (not ordinal) as above
    @Column(length = 32)
    var reason: RejectionReason? = null,

    // when the order was first created
    @Column(name = "created_at", nullable = false)
    val createdAt: Instant = Instant.now(),

    // last time the status/reason changed (bumped on every transition)
    @Column(name = "updated_at", nullable = false)
    var updatedAt: Instant = Instant.now(),
)

// saga states: PENDING/RESERVED are resumable, CONFIRMED/REJECTED are terminal
enum class OrderStatus { PENDING, RESERVED, CONFIRMED, REJECTED }

// mutually-exclusive reasons an order can end up REJECTED
enum class RejectionReason { SOLD_OUT, PAYMENT_DECLINED, RESERVATION_EXPIRED }
